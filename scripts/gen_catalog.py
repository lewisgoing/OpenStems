def package_file(package: str, *parts: str) -> Path:
    return Path(str(resources.files(package).joinpath(*parts)))


def registry_files(entry: Entry) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """Checkpoint and config artifacts (kind, name, url, sha256, size) plus registry metadata."""
    toml_path = package_file(entry.package, "config", "checkpoints.toml")
    registry = tomllib.loads(toml_path.read_text("utf-8"))["models"]
    if entry.key:
        meta = registry[entry.key]
        raw = meta.get("artifacts") or meta.get("files")
        return [dict(a) for a in raw], meta
    assert entry.files, f"{entry.id}: needs a registry key or file names"
    overrides = json.loads(package_file(entry.package, "data", "overrides.json").read_text())
    sums = json.loads(package_file(entry.package, "data", "checksums.json").read_text())["files"]
    out = []
    for kind, name in zip(("checkpoint", "config"), entry.files, strict=True):
        url = overrides["checkpoints" if kind == "checkpoint" else "configs"][name]
        out.append({"kind": kind, "name": name, "url": url, **sums[name]})
    return out, {}


def fetch(url: str, sha256: str | None) -> bytes:
    response = httpx.get(url, follow_redirects=True, timeout=60)
    response.raise_for_status()
    if sha256 and hashlib.sha256(response.content).hexdigest() != sha256:
        raise SystemExit(f"sha256 mismatch for {url}")
    return response.content


def remote_size(url: str) -> int:
    response = httpx.head(url, follow_redirects=True, timeout=60)
    response.raise_for_status()
    return int(response.headers["content-length"])


class TupleLoader(yaml.SafeLoader):
    pass


TupleLoader.add_constructor(
    "tag:yaml.org,2002:python/tuple", lambda loader, node: loader.construct_sequence(node)
)


def describe(entry: Entry) -> dict[str, Any]:
    files, meta = registry_files(entry)
    for f in files:
        if "size" not in f:  # mdxnet-infer records no sizes
            f["size"] = remote_size(f["url"])
    config_file = next((f for f in files if f["kind"] == "config"), None)
    if config_file is not None:
        config = yaml.load(fetch(config_file["url"], config_file["sha256"]), Loader=TupleLoader)
    else:
        config = meta["recipe"]
    training = config.get("training", {})
    target = training.get("target_instrument")
    stems = [target] if target else list(training.get("instruments") or meta.get("stems", []))
    inference = config.get("inference", {})
    audio = config.get("audio", {})
    chunk = int(inference.get("chunk_size") or audio.get("chunk_size") or 352800)
    hop = int(config.get("model", {}).get("stft_hop_length") or audio.get("hop_length") or 1)
    arch, loader = ARCH[entry.package]
    if arch == "mdx23c":
        hop = int(audio["hop_length"])
    names = entry.stems or [str(s).lower() for s in stems]
    if len(names) != len(stems):
        raise SystemExit(f"{entry.id}: {len(names)} names for {len(stems)} stems {stems}")
    return {
        "entry": entry,
        "architecture": arch,
        "loader": loader,
        "license": entry.license or meta.get("license") or "unrecorded",
        "variation": meta.get("variation"),
        "stems": names,
        "config_stems": [str(s) for s in stems],
        "chunk_size": chunk - chunk % hop,
        "config_chunk": chunk,
        "num_overlap": int(inference.get("num_overlap") or 2),
        "files": files,
    }


def q(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def render(info: dict[str, Any]) -> str:
    e: Entry = info["entry"]
    lines = [
        f"[models.{e.id}]",
        f"name = {q(e.name)}",
        f"use_cases = {json.dumps(e.use_cases)}",
        f"architecture = {q(info['architecture'])}",
        f"loader = {q(info['loader'])}",
        f"license = {q(info['license'])}",
    ]
    if info["variation"]:
        lines.append(f"variation = {q(info['variation'])}")
    lines.append(f"stems = {json.dumps(info['stems'])}")
    lines.append("sample_rate = 44100")
    note = ""
    if info["chunk_size"] != info["config_chunk"]:
        note = f"  # config says {info['config_chunk']}; rounded down to the STFT hop"
    lines.append(f"chunk_size = {info['chunk_size']}{note}")
    lines.append(f"num_overlap = {info['num_overlap']}")
    if e.id in MEMORY_GB:
        lines.append(f"memory_gb = {MEMORY_GB[e.id]:.2f}")
    if e.seed:
        lines.append("seed = true")
    if e.experimental:
        lines.append("experimental = true")
    if e.notes:
        lines.append(f"notes = {q(e.notes)}")
    for f in info["files"]:
        lines += [
            "",
            f"[[models.{e.id}.files]]",
            f"kind = {q(f['kind'])}",
            f"name = {q(f['name'])}",
            f"url = {q(f['url'])}",
            f"sha256 = {q(f['sha256'])}",
            f"size = {int(f['size'])}",
        ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--stems", action="store_true", help="only print each config's stems")
    args = parser.parse_args()

    blocks = []
    for entry in MODELS:
        info = describe(entry)
        print(
            f"{entry.id}: {info['config_stems']} -> {info['stems']} "
            f"chunk {info['config_chunk']} -> {info['chunk_size']} ov {info['num_overlap']}",
            file=sys.stderr,
        )
        blocks.append(render(info))
    if args.stems:
        return
    text = HEADER + "\n" + "\n\n".join(blocks) + "\n"
    if args.write:
        target = Path(__file__).resolve().parents[1] / "engine/src/openstems/catalog/models.toml"
        target.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {target}", file=sys.stderr)
    else:
        print(text)


if __name__ == "__main__":
    main()
